function getLang(): 'zh' | 'en' {
    const lang = vscode.env.language.toLowerCase();
    return lang.startsWith('zh') ? 'zh' : 'en';
}

const dict = getLang() === 'zh' ? zh : en;

/**
 * 获取国际化消息
 * @param key 消息键
 * @param args 替换参数，对应模板中的 {0}, {1}, ...
 */
export function t(key: string, ...args: (string | number)[]): string {
    let msg = dict[key];
    if (msg === undefined) {
        return key;
    }
    args.forEach((arg, i) => {
        msg = msg.replace(`{${i}}`, String(arg));
    });
    return msg;
}
